package projetoCalculadoraDeIMC;

public class Paciente {
	private float peso;
	private float altura;
	
	public float getPeso() {
		return peso;
	}
	public float getAltura() {
		return altura;
	}
	public void setPeso(float novoPeso) {
		peso = novoPeso;
	}
	public void setAltura(float novaAltura) {
		altura = novaAltura;
	}

}
