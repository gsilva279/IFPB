#02 Leia dois números e exiba a soma, subtração, multiplicação e divisão entre eles.
num1 = float(input("Informe o primeiro número: "))
num2 = float(input("Informe o segundo número: "))

soma = num1 + num2
sub = num1 - num2
mult = num1 * num2
div = num1 / num2

print(f" Soma: {soma} \n Subtração: {sub} \n Multiplicação: {mult} \n Subtração: Divisão: {div}")
