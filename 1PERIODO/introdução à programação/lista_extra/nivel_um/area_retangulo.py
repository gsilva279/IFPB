#4. Calcule a área de um retângulo com base e altura fornecidas pelo usuário.
print("###### Área do retangulo ##################")

base = float(input("Informe a base da altura em centimetros: "))
altura = float(input("Informe a altura do retangulo centimetros: "))

area_retangulo = base * altura

print(f"A área do retangulo é {area_retangulo} centimetros quadrados.")